        private static string _current = "zh-CN";
        private static Dictionary<string, string> _dict;

        public static event Action LanguageChanged;
        public static string CurrentLanguage => _current;

        static Lang() { LoadLanguage("zh-CN"); }

        public static void SetLanguage(string lang)
        {
            if (string.IsNullOrWhiteSpace(lang)) return;
            if (_current == lang && _dict != null) return;
            _current = lang;
            LoadLanguage(lang);
            LanguageChanged?.Invoke();
        }

        private static void LoadLanguage(string lang)
        {
            switch (lang)
            {
                case "en-US":
                case "en": _dict = EnUs; break;
                case "de-DE":
                case "de": _dict = DeDe; break;
                case "fr-FR":
                case "fr": _dict = FrFr; break;
                case "ru-RU":
                case "ru": _dict = RuRu; break;
                default: _dict = ZhCn; break;
            }
        }

        public static string T(string key)
        {
            if (string.IsNullOrEmpty(key)) return "";
            if (_dict != null && _dict.TryGetValue(key, out var v) && v != null) return v;
            return key;
        }

        public static string T(string key, params object[] args)
        {
            var s = T(key);
            if (args == null || args.Length == 0) return s;
            try { return string.Format(s, args); }
            catch { return s; }
        }

